_COMMIT = re.compile(r"[0-9a-f]{40}\Z")
_VERSION = re.compile(r"[0-9]+(\.[0-9]+)*([._+-]?[0-9A-Za-z]+)*\Z")
_PLATFORMS = re.compile(r"linux/(amd64|arm64)(,linux/(amd64|arm64))?\Z")
# A native build runs on a hosted runner of the architecture the binary targets.
_RUNNERS = {"linux/amd64": "ubuntu-24.04", "linux/arm64": "ubuntu-24.04-arm"}
_QUALITY_WORKFLOW = re.compile(r"\.github/workflows/[A-Za-z0-9_.-]+\.ya?ml\Z")
_ACTION_PIN = re.compile(r"(?P<repository>[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+)@(?P<commit>[0-9a-f]{40}) # "
                         r"(?P<version>[^\s#]+)\Z")
_GENERATED = re.compile(r"# Generated by Shiplord \S+\. .*regenerates this file.*\Z")
_USES = re.compile(r"(?P<prefix>\s*(?:-\s+)?uses:\s+)(?P<reference>[^\s#]+)(?P<comment>\s*(?:#.*)?)")


@dataclass(frozen=True)
class ActionPin:
    """An action pinned to a full commit, and the release that commit belongs to."""

    repository: str
    commit: str
    version: str

    def __str__(self) -> str:
        return f"{self.repository}@{self.commit} # {self.version}"


def parse_action_pin(value: str) -> ActionPin:
    """Read ``owner/repository@<40 hex> # <version>``, the form every pin is written in."""
    match = _ACTION_PIN.fullmatch(value)
    if match is None:
        raise ValueError("an action pin is repository@<40-character commit> # <version>")
    return ActionPin(match.group("repository"), match.group("commit"), match.group("version"))


