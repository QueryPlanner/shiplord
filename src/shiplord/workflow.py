class WorkflowError(ValueError):
    """The workflow cannot be generated for this manifest."""


def validate_quality_workflow(path: object) -> str:
    """Return a quality workflow path that is safe to reference, or raise ``WorkflowError``.

    Only a reusable workflow file inside ``.github/workflows`` may be called, and never one Shiplord
    generates: a pipeline cannot call itself.
    """
    if not isinstance(path, str) or not _QUALITY_WORKFLOW.fullmatch(path) or path in (WORKFLOW_PATH, DEPLOY_WORKFLOW_PATH):
        raise WorkflowError("the quality workflow must be a reusable workflow file under .github/workflows/, "
                            "and not a workflow Shiplord generates")
    return path


def validate_platforms(runtime: str, platforms: str) -> None:
    """Reject a platform request the generated workflow cannot satisfy."""
    if not _PLATFORMS.fullmatch(platforms):
        raise WorkflowError("platforms must be linux/amd64, linux/arm64, or both separated by a comma")
    if runtime == "native" and "," in platforms:
        raise WorkflowError("a native workflow builds one binary; choose linux/amd64 or linux/arm64")


def native_build_settings(manifest: dict) -> tuple[str, str]:
    """The validated command and binary path a native workflow needs, or a refusal naming both."""
    github = manifest.get("github") or {}
    command, path = github.get("build_command"), github.get("binary_path")
    if not command or not path:
        raise WorkflowError("a native application needs the command that builds its binary and the path it writes: "
                            "pass --build-command and --binary-path, or add github.build_command and "
                            "github.binary_path to ship.toml")
    try:
        return validate_build_command(command), validate_binary_path(path)
    except ManifestError as error:
        raise WorkflowError(str(error)) from None


def _validate(manifest: dict, tooling_ref: str | None, tooling_version: str | None, platforms: str,
              tooling_repository: str, *, allow_native: bool = False) -> None:
    runtime = manifest["runtime"]
    if runtime not in ("docker", "native"):
        raise WorkflowError("runtime must be docker or native")
    if runtime == "native" and not allow_native:
        raise WorkflowError("workflow generation is available for Docker applications; for a native binary, call "
                            "`shiplord deploy --binary` from your own build job")
    if (tooling_ref is None) == (tooling_version is None):
        raise WorkflowError("pin Shiplord by exactly one of a commit or a PyPI version")
    if tooling_ref is not None and not _COMMIT.fullmatch(tooling_ref):
        raise WorkflowError("the tooling reference must be a full 40-character commit SHA")
    if tooling_version is not None and not _VERSION.fullmatch(tooling_version):
        raise WorkflowError("the tooling version must be a PyPI version such as 0.2.0")
    validate_platforms(runtime, platforms)
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", tooling_repository):
        raise WorkflowError("invalid tooling repository")


def _tooling_install(tooling_ref: str | None, tooling_version: str | None, tooling_repository: str) -> str:
    """The pip requirement the deploy job installs: a PyPI release, or a commit of the tooling repository."""
    if tooling_version is not None:
        return f"shiplord=={tooling_version}"
    return f"git+https://github.com/{tooling_repository}.git@{tooling_ref}"



def _header() -> str:
    return (f"# Generated by Shiplord {__version__}. `shiplord github setup` regenerates this file; "
            "review changes in a pull request.\n")


def render_deploy_workflow(manifest: dict, *, tooling_ref: str | None = None, tooling_version: str | None = None,
                           tooling_repository: str = TOOLING_REPOSITORY,
                           platforms: str = "linux/amd64") -> str:
    """Return the reusable deploy workflow. Deterministic: the same inputs always produce the same bytes."""
    _validate(manifest, tooling_ref, tooling_version, platforms, tooling_repository)
    branch = configured_branch(manifest)
    branch_ref = ("refs/heads/" + branch).replace("'", "''")
    quote = json.dumps
    install = _tooling_install(tooling_ref, tooling_version, tooling_repository)
    qemu = f"      - uses: {ACTIONS['qemu']}\n" if "arm64" in platforms else ""
    # The deploy job's tailnet, SSH, deploy and summary steps live in this repository's composite action,
    # pinned to the CLI commit for git installs, or an independent reviewed commit for PyPI installs.
    action_repository = TOOLING_REPOSITORY if tooling_version is not None else tooling_repository
    action_ref = PYPI_DEPLOY_ACTION_REF if tooling_version is not None else tooling_ref
    action = f"{action_repository}/deploy@{action_ref}"
    return _header() + f"""name: Shiplord deploy

on:
  workflow_call:
    inputs:
      check_only:
        description: Check CI access only (Tailscale, SSH, helper); build and deploy nothing
        type: boolean
        default: false
    secrets:
      SHIPLORD_SSH_PRIVATE_KEY:
        required: true

permissions:
  contents: read

jobs:
  build:
    if: ${{{{ !inputs.check_only }}}}
    runs-on: ubuntu-24.04
    timeout-minutes: 30
    permissions:
      contents: read
      packages: write
    outputs:
      digest: ${{{{ steps.build-push.outputs.digest }}}}
      image: ${{{{ steps.name.outputs.image }}}}
    steps:
      - uses: {ACTIONS['checkout']}
        with:
          persist-credentials: false
      - name: Image name
        id: name
        run: echo "image=ghcr.io/${{GITHUB_REPOSITORY,,}}" >> "$GITHUB_OUTPUT"
{qemu}      - uses: {ACTIONS['buildx']}
      - uses: {ACTIONS['login']}
        with:
          registry: ghcr.io
          username: ${{{{ github.actor }}}}
          password: ${{{{ secrets.GITHUB_TOKEN }}}}
      - name: Image metadata
        id: meta
        uses: {ACTIONS['metadata']}
        with:
          images: ${{{{ steps.name.outputs.image }}}}
          tags: type=sha,format=long
      - name: Build and push
        id: build-push
        uses: {ACTIONS['build']}
        with:
          context: .
          push: true
          platforms: {platforms}
          tags: ${{{{ steps.meta.outputs.tags }}}}
          labels: |
            ${{{{ steps.meta.outputs.labels }}}}
            org.opencontainers.image.revision=${{{{ github.sha }}}}

  deploy:
    needs: build
    # Runs after a successful build, or alone for a check-only call (which skips the build).
    if: ${{{{ !cancelled() && github.ref == '{branch_ref}' && (inputs.check_only || needs.build.result == 'success') }}}}
    runs-on: ubuntu-24.04
    timeout-minutes: 30
    permissions:
      contents: read
      id-token: write
    steps:
      - uses: {ACTIONS['checkout']}
        with:
          ref: ${{{{ github.sha }}}}
          persist-credentials: false
      - name: Verify the checked-out commit
        run: test "$(git rev-parse HEAD)" = "$GITHUB_SHA"
      - uses: {ACTIONS['python']}
        with:
          python-version: "3.12"
      - name: Install the pinned Shiplord
        run: python -m pip install --disable-pip-version-check {quote(install)}
      - name: Deploy with Shiplord
        uses: {action}
        with:
          check-only: ${{{{ inputs.check_only }}}}
          ssh-private-key: ${{{{ secrets.SHIPLORD_SSH_PRIVATE_KEY }}}}
          ssh-known-hosts: ${{{{ vars.SHIPLORD_SSH_KNOWN_HOSTS }}}}
          deploy-user: ${{{{ vars.SHIPLORD_DEPLOY_USER }}}}
          server-host: ${{{{ vars.SHIPLORD_SERVER_HOST }}}}
          ssh-port: ${{{{ vars.SHIPLORD_SSH_PORT }}}}
          ts-client-id: ${{{{ vars.SHIPLORD_TS_CLIENT_ID }}}}
          ts-audience: ${{{{ vars.SHIPLORD_TS_AUDIENCE }}}}
          ts-tags: ${{{{ vars.SHIPLORD_TS_TAGS || 'tag:ci' }}}}
          image: ${{{{ needs.build.outputs.image }}}}
          digest: ${{{{ needs.build.outputs.digest }}}}
          commit: ${{{{ github.sha }}}}
          request-id: gh-${{{{ github.run_id }}}}-${{{{ github.run_attempt }}}}
"""


def _native_build_job(command: str, path: str, runner: str) -> str:
    quote = json.dumps
    return f"""  build:
    # A native application runs its own checks; this workflow only builds the binary and deploys it.
    if: ${{{{ !inputs.check_only }}}}
    runs-on: {runner}
    timeout-minutes: 30
    permissions:
      contents: read
    steps:
      - uses: {ACTIONS['checkout']}
        with:
          persist-credentials: false
      - name: Build the binary
        env:
          BINARY_PATH: {quote(path)}
        run: |
          set -euo pipefail
          {command}
          test -s "$GITHUB_WORKSPACE/$BINARY_PATH"   # the build must write the binary where ship.toml says
      - name: Upload the binary
        uses: {ACTIONS['upload-artifact']}
        with:
          name: shiplord-binary
          path: {quote(path)}
          if-no-files-found: error
          retention-days: 1
"""


def _native_download_step() -> str:
    return f"""      - name: Download the binary
        if: ${{{{ !inputs.check_only }}}}
        uses: {ACTIONS['download-artifact']}
        with:
          name: shiplord-binary
          path: ${{{{ runner.temp }}}}/shiplord-binary
"""


def _native_deploy_step(path: str) -> str:
    basename = path.rsplit("/", 1)[-1]
    return f"""      - name: Deploy
        if: ${{{{ !inputs.check_only }}}}
        env:
          BINARY: ${{{{ runner.temp }}}}/shiplord-binary/{basename}
          RUN_ID: ${{{{ github.run_id }}}}
          RUN_ATTEMPT: ${{{{ github.run_attempt }}}}
        run: |
          set -euo pipefail
          shiplord deploy --binary "$BINARY" --commit "$GITHUB_SHA" \\
            --request-id "gh-${{RUN_ID}}-${{RUN_ATTEMPT}}" --require-public --json | tee "$RUNNER_TEMP/shiplord-result.json"
"""


def _native_deploy_job(branch_ref: str, install: str, path: str) -> str:
    quote = json.dumps
    return f"""  deploy:
    needs: build
    # Runs after a successful build, or alone for a check-only dispatch (which skips the build).
    if: ${{{{ !cancelled() && github.ref == '{branch_ref}' && (inputs.check_only || needs.build.result == 'success') }}}}
    runs-on: ubuntu-24.04
    timeout-minutes: 30
    permissions:
      contents: read
      id-token: write
    steps:
      - uses: {ACTIONS['checkout']}
        with:
          ref: ${{{{ github.sha }}}}
          persist-credentials: false
      - name: Verify the checked-out commit
        run: test "$(git rev-parse HEAD)" = "$GITHUB_SHA"
{_native_download_step()}      - uses: {ACTIONS['python']}
        with:
          python-version: "3.12"
      - name: Install the pinned Shiplord
        run: python -m pip install --disable-pip-version-check {quote(install)}
      - name: Join the tailnet
        uses: {ACTIONS['tailscale']}
        with:
          oauth-client-id: ${{{{ vars.SHIPLORD_TS_CLIENT_ID }}}}
          audience: ${{{{ vars.SHIPLORD_TS_AUDIENCE }}}}
          tags: ${{{{ vars.SHIPLORD_TS_TAGS || 'tag:ci' }}}}
          # A new node is not accepted by its peers immediately; wait until the server answers.
          ping: ${{{{ vars.SHIPLORD_SERVER_HOST }}}}
      - name: Prepare the SSH identity and pinned host keys
        env:
          SSH_PRIVATE_KEY: ${{{{ secrets.SHIPLORD_SSH_PRIVATE_KEY }}}}
          KNOWN_HOSTS: ${{{{ vars.SHIPLORD_SSH_KNOWN_HOSTS }}}}
          DEPLOY_USER: ${{{{ vars.SHIPLORD_DEPLOY_USER }}}}
          SERVER_HOST: ${{{{ vars.SHIPLORD_SERVER_HOST }}}}
          SSH_PORT: ${{{{ vars.SHIPLORD_SSH_PORT }}}}
        run: |
          set -euo pipefail
          umask 077
          printf '%s\\n' "$SSH_PRIVATE_KEY" > "$RUNNER_TEMP/shiplord_key"
          printf '%s\\n' "$KNOWN_HOSTS" > "$RUNNER_TEMP/shiplord_known_hosts"
          {{
            echo "SHIPLORD_SSH_IDENTITY=$RUNNER_TEMP/shiplord_key"
            echo "SHIPLORD_SSH_KNOWN_HOSTS_FILE=$RUNNER_TEMP/shiplord_known_hosts"
            echo "SHIPLORD_SSH_TARGET=${{DEPLOY_USER}}@${{SERVER_HOST}}"
            if [ -n "$SSH_PORT" ]; then echo "SHIPLORD_SSH_PORT=$SSH_PORT"; fi
          }} >> "$GITHUB_ENV"
      - name: Check access only
        if: ${{{{ inputs.check_only }}}}
        run: shiplord status --json
{_native_deploy_step(path)}      - name: Summary
        if: ${{{{ always() }}}}
        run: |
          python - <<'PY'
          import json, os
          path = os.path.join(os.environ["RUNNER_TEMP"], "shiplord-result.json")
          if os.path.exists(path):
              result = json.load(open(path))
              release = result.get("release") or {{}}
              lines = [f"- status: {{result.get('status')}}", f"- commit: {{release.get('commit')}}",
                       f"- public check: {{(result.get('public') or {{}}).get('ok')}}"]
              open(os.environ["GITHUB_STEP_SUMMARY"], "a").write("### Shiplord deployment\\n" + "\\n".join(lines) + "\\n")
          PY
      - name: Remove the SSH identity
        if: ${{{{ always() }}}}
        run: rm -f "$RUNNER_TEMP/shiplord_key" "$RUNNER_TEMP/shiplord_known_hosts" "$RUNNER_TEMP/shiplord-result.json"
"""


def _native_workflow(manifest: dict, *, tooling_ref: str | None, tooling_version: str | None,
                     tooling_repository: str, platforms: str) -> str:
    """One file for a native application: the build job and the deploy job run in the same workflow."""
    command, path = native_build_settings(manifest)
    install = _tooling_install(tooling_ref, tooling_version, tooling_repository)
    branch = configured_branch(manifest)
    app = manifest["name"]
    quote = json.dumps
    branch_ref = ("refs/heads/" + branch).replace("'", "''")
    return _header() + f"""name: Release

on:
  push:
    branches: [{quote(branch)}]
  workflow_dispatch:
    inputs:
      check_only:
        description: Check CI access only (Tailscale, SSH, helper); build and deploy nothing
        type: boolean
        default: false

permissions:
  contents: read

# Production releases run one at a time and are never cancelled half way.
concurrency:
  group: {quote("shiplord-release-" + app)}
  cancel-in-progress: false

jobs:
{_native_build_job(command, path, _RUNNERS[platforms])}
{_native_deploy_job(branch_ref, install, path)}"""


def render_workflow(manifest: dict, *, tooling_ref: str | None = None, tooling_version: str | None = None,
                    tooling_repository: str = TOOLING_REPOSITORY,
                    platforms: str = "linux/amd64", quality_workflow: str | None = None) -> str:
    """Return the trigger workflow text. Deterministic: the same inputs always produce the same bytes.

    ``quality_workflow`` is a reusable workflow in this repository to run before deploy, or ``None`` for a
    pipeline with no quality job. It is never guessed here: the caller decides from the project. A native
    application gets one self-contained file and has no quality job.
    """
    _validate(manifest, tooling_ref, tooling_version, platforms, tooling_repository, allow_native=True)
    if manifest["runtime"] == "native":
        if quality_workflow is not None:
            raise WorkflowError("a native workflow has no quality job; run your checks in the build command")
        return _native_workflow(manifest, tooling_ref=tooling_ref, tooling_version=tooling_version,
                                tooling_repository=tooling_repository, platforms=platforms)
    quality = None if quality_workflow is None else validate_quality_workflow(quality_workflow)
    branch = configured_branch(manifest)
    app = manifest["name"]
    quote = json.dumps
    if quality is None:
        quality_job, deploy_needs, deploy_if = "", "", "    if: ${{ !cancelled() }}\n"
    else:
        quality_job = (f"""  quality:
    if: ${{{{ !inputs.check_only }}}}
    permissions:
      contents: read
      id-token: write
    uses: ./{quality}

""")
        deploy_needs = "    needs: quality\n"
        deploy_if = "    if: ${{ !cancelled() && (inputs.check_only || needs.quality.result == 'success') }}\n"
    return _header() + f"""name: Release

on:
  push:
    branches: [{quote(branch)}]
  workflow_dispatch:
    inputs:
      check_only:
        description: Check CI access only (Tailscale, SSH, helper); build and deploy nothing
        type: boolean
        default: false

permissions:
  contents: read

# Production releases run one at a time and are never cancelled half way.
concurrency:
  group: {quote("shiplord-release-" + app)}
  cancel-in-progress: false

jobs:
{quality_job}  deploy:
{deploy_needs}{deploy_if}    permissions:
      contents: read
      id-token: write
      packages: write
    uses: ./{DEPLOY_WORKFLOW_PATH}
    with:
      check_only: ${{{{ inputs.check_only }}}}
    secrets:
      SHIPLORD_SSH_PRIVATE_KEY: ${{{{ secrets.SHIPLORD_SSH_PRIVATE_KEY }}}}
"""


# --- refreshing the pins ----------------------------------------------------------------

def is_generated_workflow(text: str) -> bool:
    """Whether the first line is the header Shiplord writes; only such a file may be rewritten."""
    return bool(_GENERATED.fullmatch(text.split("\n", 1)[0]))


@dataclass(frozen=True)
class PinChange:
    """One ``uses:`` line rewritten from an older reference to the current pin."""

    repository: str
    previous: str
    commit: str
    version: str


def upgrade_action_pins(text: str, *, pins: Mapping[str, ActionPin] | None = None) -> tuple[str, list[PinChange]]:
    """Return the workflow with its action pins refreshed, and what changed.

    Only ``uses:`` lines naming an action Shiplord pins are rewritten, so the deployment branch, the pinned
    Shiplord commit, the quality job and every other local edit survive byte for byte. A file that does not
    carry Shiplord's header is refused: a hand-written workflow is never touched.
    """
    managed = {pin.repository: pin for pin in (PINS if pins is None else pins).values()}
    if not is_generated_workflow(text):
        raise WorkflowError("this file does not carry the header Shiplord writes, so it was not generated by "
                            "Shiplord and is left alone")
    lines, changes = [], []
    for line in text.splitlines(keepends=True):
        body = line.rstrip("\r\n")
        ending = line[len(body):]
        match = _USES.fullmatch(body)
        if match is not None:
            repository, _, reference = match.group("reference").partition("@")
            pin = managed.get(repository)
            if pin is not None and reference != pin.commit:
                changes.append(PinChange(repository, reference, pin.commit, pin.version))
                body = f"{match.group('prefix')}{pin}"
        lines.append(body + ending)
    upgraded = "".join(lines)
    _verify_upgrade(text, upgraded, managed)
    return upgraded, list(dict.fromkeys(changes))  # one entry per distinct change, not per line


def _verify_upgrade(before: str, after: str, managed: Mapping[str, ActionPin]) -> None:
    """Prove the rewrite touched only pin lines for actions Shiplord manages, or raise ``WorkflowError``."""
    if not is_generated_workflow(after):
        raise WorkflowError("the refreshed workflow lost its Shiplord header")
    old_lines, new_lines = before.splitlines(keepends=True), after.splitlines(keepends=True)
    if len(old_lines) != len(new_lines):
        raise WorkflowError("the refreshed workflow changed shape")
    for old, new in zip(old_lines, new_lines):
        if old == new:
            continue
        body = new.rstrip("\r\n")
        match = _USES.fullmatch(body)
        pin = None if match is None else managed.get(match.group("reference").partition("@")[0])
        if pin is None or body != f"{match.group('prefix')}{pin}":
            raise WorkflowError("the refreshed workflow would change a line Shiplord does not manage")


# --- checking the pins ------------------------------------------------------------------

@dataclass(frozen=True)
class PinReport:
    """What the GitHub API said about one pin: ``resolves``, ``missing``, or ``unverified``."""

    repository: str
    commit: str
    version: str
    state: str
    detail: str | None = None

    @property
    def reference(self) -> str:
        return f"{self.repository}@{self.commit} ({self.version})"


def github_fetch(url: str, token: str | None = None, *, timeout: float = 20) -> tuple[int, str]:
    """GET a GitHub API URL; return (status, body). A network failure raises ``OSError``."""
    headers = {"Accept": "application/vnd.github+json", "User-Agent": f"shiplord/{__version__}",
               "X-GitHub-Api-Version": "2022-11-28"}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    try:
        with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=timeout) as response:
            return response.status, response.read(65536).decode("utf-8", "replace")
    except urllib.error.HTTPError as error:
        with error:
            return error.code, error.read(4096).decode("utf-8", "replace")


def check_action_pins(*, pins: Mapping[str, ActionPin] | None = None, token: str | None = None,
                      fetch: Callable[[str, str | None], tuple[int, str]] | None = None) -> tuple[int, dict]:
    """Confirm every pinned commit still belongs to the action's own repository.

    ``GET /repos/{owner}/{repository}/commits/{commit}`` answers 200 only for a commit in that repository, so
    a pin that was deleted, mistyped, or moved to another repository fails the check. When the API cannot be
    asked - no network, a refused token, a rate limit - the pin is reported as unverified, never as resolving.
    """
    request = github_fetch if fetch is None else fetch
    reports = []
    for pin in (PINS if pins is None else pins).values():
        url = f"{GITHUB_API}/repos/{pin.repository}/commits/{pin.commit}"
        try:
            status, _body = request(url, token)
        except OSError:
            reports.append(PinReport(pin.repository, pin.commit, pin.version, "unverified",
                                     "the GitHub API could not be reached"))
            continue
        if status == 200:
            reports.append(PinReport(pin.repository, pin.commit, pin.version, "resolves"))
        elif status in (404, 422):
            reports.append(PinReport(pin.repository, pin.commit, pin.version, "missing",
                                     "the repository has no such commit"))
        else:
            reports.append(PinReport(pin.repository, pin.commit, pin.version, "unverified",
                                     f"the GitHub API answered {status}"))
    missing = [report.reference for report in reports if report.state == "missing"]
    unverified = [report.reference for report in reports if report.state == "unverified"]
    result = {"ok": not missing and not unverified, "checked": len(reports), "missing": missing,
              "unverified": unverified,
              "pins": [{"action": report.repository, "commit": report.commit, "version": report.version,
                        "state": report.state} | ({"detail": report.detail} if report.detail else {})
                       for report in reports]}
    if missing:
        result["error"] = ("a pinned action commit does not resolve in its repository; refresh the pins with "
                           "`shiplord github setup --upgrade-workflow`")
    elif unverified:
        result["error"] = ("the GitHub API could not be asked about every pin, so nothing here says they "
                           "resolve")
    return (0 if result["ok"] else 1), result
